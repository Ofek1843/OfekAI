export function detectBrowserLanguage() {
  const supported = getSupportedLanguages();

  const languages =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];

  for (const language of languages) {
    const short = language.toLowerCase().split("-")[0];

    if (supported.includes(short)) {
      return short;
    }
  }

  return "en";
}

export function getLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);

  if (
    saved &&
    getSupportedLanguages().includes(saved)
  ) {
    return saved;
  }

  // Keep first visits predictable and globally consistent. Visitors can still
  // choose any supported language from the landing-page welcome dialog.
  return "en";
}

export function setLanguage(lang) {
  const supported = getSupportedLanguages();

  const current = supported.includes(lang)
    ? lang
    : "en";

  localStorage.setItem(
    STORAGE_KEY,
    current
  );

  document.documentElement.lang = current;
  document.documentElement.dir =
    isRTL(current) ? "rtl" : "ltr";

  return current;
}

