const STORAGE_KEY = "ofek-ai-language";

export function t(lang, key) {
  return (
    translations?.[lang]?.[key] ??
    translations.en?.[key] ??
    key
  );
}

export function getSupportedLanguages() {
  return Object.keys(translations);
}

export function isRTL(lang) {
  return ["he", "ar"].includes(lang);
}

export function detectBrowserLanguage() {
  const supported = getSupportedLanguages();

  const languages =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];

  for (const language of languages) {
    const short = language.toLowerCase().split("-")[0];

    if (supported.includes(short)) {
      return short;
    }
  }

  return "en";
}

export function getLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);

  if (
    saved &&
    getSupportedLanguages().includes(saved)
  ) {
    return saved;
  }

  // English is the explicit product default. A browser locale is not a user
  // preference and must never switch a new or anonymous visitor into Hebrew.
  return "en";
}

export function setLanguage(lang) {
  const supported = getSupportedLanguages();

  const current = supported.includes(lang)
    ? lang
    : "en";

  localStorage.setItem(
    STORAGE_KEY,
    current
  );

  document.documentElement.lang = current;
  document.documentElement.dir =
    isRTL(current) ? "rtl" : "ltr";

  return current;
}

export function initializeLanguage() {
  return setLanguage(getLanguage());
}
