export function escapeHtml(value = "") {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#039;");
}

export function initials(profile = {}) {
  const source = String(profile.displayName || profile.username || "FP").trim();
  return source.split(/\s+/).filter(Boolean).slice(0, 2).map((part) => [...part][0]).join("").toUpperCase() || "FP";
}

export function timestampMs(value) {
  if (!value) return 0;
  if (typeof value.toMillis === "function") return value.toMillis();
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

export function formatMessageTime(value, language = "en") {
  const ms = timestampMs(value);
  if (!ms) return "";
  return new Intl.DateTimeFormat(language === "he" ? "he-IL" : "en-US", { hour: "2-digit", minute: "2-digit" }).format(new Date(ms));
}

export function mergeMessages(current = [], incoming = []) {
  const byId = new Map(current.map((message) => [message.id, message]));
  for (const message of incoming) {
    if (message.clientId) {
      for (const [id, existing] of byId) {
        if (id !== message.id && existing.clientId === message.clientId && String(id).startsWith("sending_")) byId.delete(id);
      }
    }
    byId.set(message.id, { ...byId.get(message.id), ...message });
  }
  return [...byId.values()].sort((a, b) => timestampMs(a.createdAt) - timestampMs(b.createdAt));
}

export function graphPolyline(points = [], width = 720, height = 260, padding = 28) {
  const numeric = points.filter((point) => Number.isFinite(Number(point.value)));
  if (numeric.length < 2) return "";
  const values = numeric.map((point) => Number(point.value));
  const min = Math.min(...values);
  const max = Math.max(...values);
  const range = max - min || 1;
  return numeric.map((point, index) => {
    const x = padding + index * (width - padding * 2) / Math.max(1, numeric.length - 1);
    const y = height - padding - (Number(point.value) - min) / range * (height - padding * 2);
    return `${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`;
  }).join(" ");
}

export function safeClientId() {
  if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID().replaceAll("-", "_");
  return `msg_${Date.now()}_${Math.random().toString(36).slice(2, 12)}`;
}
