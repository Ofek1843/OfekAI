"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { ORIGIN, features, hub } = require("./seo-feature-content");
const escape = value => String(value).replace(/[&<>"']/g, character => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
}[character]));

// Reuse the actual homepage preview components, including their sample values.
// Build-time adapter only: no eval, browser execution or account data access.
// Fail the build if that component contract changes rather than publish a blank.
function previewMarkup(kind) {
  if (kind === "progress") {
    const source = fs.readFileSync(path.join(__dirname, "../public/progress.html"), "utf8");
    const summary = source.match(/<section class="stats-grid">([\s\S]*?)<\/section>/)?.[1];
    const chart = source.match(/<section class="chart-card">([\s\S]*?)<\/section>/)?.[1];
    if (!summary || !chart) throw new Error("Progress preview contract changed");
    return `<div class="progress-preview">${summary}${chart}</div>`
      .replace(/\s+id="[^"]*"/g, "")
      .replace(/[ \t]+$/gm, "");
  }
  if (kind === "tracker") {
    const source = fs.readFileSync(path.join(__dirname, "../public/workout-tracker.html"), "utf8");
    const timer = source.match(/<div class="rest-strip">([\s\S]*?)<\/div>\s*<p id="restHint">([\s\S]*?)<\/p>\s*<\/div>/);
    if (!timer) throw new Error("Workout rest-timer preview contract changed");
    return previewMarkup("workout") + `<div class="tracker-preview">${timer[1]}</div><p>${timer[2]}</p></div>`.replace(/\s+id="[^"]*"/g, "");
  }
  const index = { workout: 0, nutrition: 1, diary: 2 }[kind];
  if (index === undefined) throw new Error(`Unknown product preview: ${kind}`);
  const source = fs.readFileSync(path.join(__dirname, "../public/js/simple-ux.js"), "utf8");
  const template = source.match(new RegExp(`if\\(index===${index}\\) demo\\.innerHTML=\\x60([^\\x60]+)\\x60;`))?.[1];
  if (!template) throw new Error(`Homepage preview ${kind} changed; update the SEO adapter`);
  const html = template.replace(/\$\{label\('([^']*)','[^']*'\)\}/g, (_, english) => escape(english));
  if (html.includes("${")) throw new Error(`Unresolved preview expression: ${kind}`);
  // Dimensions reserve space; source images remain lazy (noncritical samples).
  return html
    .replace(/(\/images\/exercises\/(?:bench-press|seated-cable-row))\.png/g, "$1.webp")
    .replace(/<img /g, '<img width="95" height="80" decoding="async" ');
}

function card(feature) {
  return `<article class="feature-card"><p class="eyebrow">${escape(feature.label)}</p>
<h3><a href="${feature.route}">${escape(feature.h1)}</a></h3>
<p>${escape(feature.intro)}</p><a class="text-link" href="${feature.route}">Explore ${escape(feature.label.toLowerCase())} <span aria-hidden="true">→</span></a></article>`;
}

