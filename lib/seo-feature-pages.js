<nav aria-label="Footer"><a href="/features">All features</a><a href="/exercise-library">Exercise library</a><a href="/about.html">About</a><a href="/faq.html">Help &amp; FAQ</a><a href="/contact.html">Contact</a><a href="/privacy.html">Privacy</a><a href="/terms.html">Terms</a><a href="/privacy.html#analytics-choices">Analytics preferences</a></nav>
